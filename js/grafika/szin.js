const sm = t => t * t * (3 - 2 * t);
const lerp = (a, b, t) => a + (b - a) * t;
const lerp3 = (a, b, t) => [lerp(a[0], b[0], t), lerp(a[1], b[1], t), lerp(a[2], b[2], t)];

/** A színkorrekció az adott órára: {exposure, wb, contrast, saturation, shadowTint, highTint, lift, szoras, bloom} */
export function napszakSzin(ora) {
  ora = ((ora % 24) + 24) % 24;
  let i = 0; while (i < K.length - 2 && K[i + 1][0] <= ora) i++;
  const a = K[i], b = K[i + 1], t = sm(Math.min(1, Math.max(0, (ora - a[0]) / (b[0] - a[0]))));
  return {
    exposure: lerp(a[1], b[1], t), wb: lerp3(a[2], b[2], t), contrast: lerp(a[3], b[3], t), saturation: lerp(a[4], b[4], t),
    shadowTint: lerp3(a[5], b[5], t), highTint: lerp3(a[6], b[6], t), lift: lerp3(a[7], b[7], t), szoras: lerp(a[8], b[8], t), bloom: lerp(a[9], b[9], t),
  };
}
